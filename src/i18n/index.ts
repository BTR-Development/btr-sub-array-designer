/**
 * Exported so the parity test can walk every dictionary. English is empty
 * because `translate` falls back to `EN` itself; a key listed here but absent
 * from a dictionary is a gap, not a bug in the lookup.
 */
export const DICTS: Record<Lang, Partial<Record<MessageKey, string>>> = { en: {}, pl: PL, it: IT };

export type Vars = Record<string, string | number>;

/** Look a message up, falling back to English, and fill in any {placeholders}. */
export function translate(lang: Lang, key: MessageKey, vars?: Vars): string {
  const raw = DICTS[lang][key] ?? EN[key];
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, name: string) =>
    name in vars ? String(vars[name]) : m,
  );
}
